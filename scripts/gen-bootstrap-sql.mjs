#!/usr/bin/env node
// Embeds prisma/migrations/*_init/migration.sql into lib/db-bootstrap-sql.ts so the
// runtime auto-bootstrap works on Vercel without relying on files being traced
// into each serverless function. Run after regenerating the init migration:
//   node scripts/gen-bootstrap-sql.mjs
// tests/db-bootstrap.test.ts fails if the two drift apart.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const migrationsDir = path.join(root, "prisma", "migrations");
const initDir = fs.readdirSync(migrationsDir).filter((d) => d.endsWith("_init")).sort()[0];
if (!initDir) throw new Error("No *_init migration found in prisma/migrations");
const sql = fs.readFileSync(path.join(migrationsDir, initDir, "migration.sql"), "utf8");

const out = `// AUTO-GENERATED by scripts/gen-bootstrap-sql.mjs — do not edit by hand.
// Source: prisma/migrations/${initDir}/migration.sql
export const INIT_MIGRATION_NAME = ${JSON.stringify(initDir)};
export const INIT_MIGRATION_SQL = ${JSON.stringify(sql)};
`;
fs.writeFileSync(path.join(root, "lib", "db-bootstrap-sql.ts"), out);
console.log(`lib/db-bootstrap-sql.ts written from ${initDir} (${sql.length} bytes)`);
